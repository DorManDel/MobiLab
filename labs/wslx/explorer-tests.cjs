/* Node regression tests for shared virtual filesystem and shell navigation. */
const assert=require('node:assert/strict'),nodefs=require('node:fs'),vm=require('node:vm');
const sandbox={window:{},console};vm.createContext(sandbox);
for(const file of ['src/terminal-engine.js','src/commands-linux.js','src/commands-wslx.js'])vm.runInContext(nodefs.readFileSync(file,'utf8'),sandbox,{filename:file});
const W=sandbox.window.WSLXLab, t=new W.TerminalEngine();W.installLinux(t);W.installWSLX(t);
const fs=t.fs;
(async()=>{
  const updates=[];t.subscribe(()=>updates.push(t.cwd));
  assert.equal(fs.get('/home/dor/projects/wslx').kind,'dir');
  fs.mkdir('/home/dor/projects/new folder');
  fs.writeFile('/home/dor/projects/new folder/log.txt','Hello explorer',{create:true});
  assert.equal(fs.get('/home/dor/projects/new folder/log.txt').content,'Hello explorer');
  await t.execute("wcd '/home/dor/projects/new folder'");
  assert.equal(t.cwd,'/home/dor/projects/new folder');
  assert.equal(updates.at(-1),t.cwd);
  let snapshot=fs.snapshot();
  fs.move('/home/dor/projects/new folder','/mnt/d/Projects/Explorer');
  assert.equal(fs.get('/mnt/d/Projects/Explorer/log.txt').content,'Hello explorer');
  assert.equal(fs.get('/home/dor/projects/new folder'),undefined);
  assert.throws(()=>fs.move('/mnt/d/Projects','/mnt/d/Projects/inside'),/into itself/);
  assert.throws(()=>fs.move('/home/dor','/mnt/d/Projects/Explorer'),/already exists/);
  assert.throws(()=>fs.writeFile('/mnt/d/Projects/Explorer','abc'),/directory/);
  assert.throws(()=>fs.mkdir('/mnt/d/Projects/Explorer/log.txt/child'),/parent|exists/i);
  fs.restore(snapshot);
  assert.equal(fs.get('/home/dor/projects/new folder/log.txt').content,'Hello explorer');
  const data=fs.exportData();
  fs.remove('/home/dor/projects/new folder');
  assert.equal(fs.get('/home/dor/projects/new folder'),undefined);
  fs.importData(data);
  assert.equal(fs.get('/home/dor/projects/new folder/log.txt').content,'Hello explorer');
  const before=JSON.stringify(fs.exportData());
  assert.throws(()=>fs.importData({format:'wslx-lab-v1',entries:[['/home/dor/a',{kind:'file',content:'x'}]]}),/required|missing/i);
  assert.equal(JSON.stringify(fs.exportData()),before);
  const bad={format:'wslx-lab-v1',entries:JSON.parse(JSON.stringify(data.entries))};
  bad.entries.push(['/home/dor/../../etc/passwd',{kind:'file',content:'bad'}]);
  assert.throws(()=>fs.importData(bad),/invalid/i);
  fs.writeFile('/home/dor/projects/new folder/log.txt','Updated from explorer');
  await t.execute('cd /home/dor');
  await t.execute("wcd '/home/dor/projects/new folder'");
  const result=await t.execute('cat log.txt');
  assert.match(result.lines.map(l=>l.text).join('\n'),/Updated from explorer/);
  assert.equal(t.toWindows('/mnt/d/Projects/Explorer'),'D:\\Projects\\Explorer');
  assert.equal(t.path('C:\\Users\\Dor\\Projects'),'/mnt/c/Users/Dor/Projects');
  console.log('PASS R0.3: shared explorer FS, cwd sync, moves, undo snapshot, guarded restore, Windows mapping');
})().catch(e=>{console.error(e);process.exitCode=1});