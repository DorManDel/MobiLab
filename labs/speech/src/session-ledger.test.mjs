import assert from "node:assert/strict";
import {SessionLedger,dedupeFinalOverlap,ProviderCircuit} from "./session-ledger.js";
const log=new SessionLedger();
const first=log.append({id:1,at:1000,offset:0,text:"hello one",source:"en",target:"he",results:{}});
log.append({id:2,at:2000,offset:1000,text:"hello two",source:"en",target:"he",results:{cloud:{status:"error",error:"HTTP 429"}}});
assert.equal(log.focused.id,2);
assert.equal(log.focus(1).id,1);
log.append({id:3,at:3000,offset:2000,text:"hello three",source:"en",target:"he",results:{}});
assert.equal(log.focused.id,1,"Manual focus must not jump while new transcript arrives");
assert.equal(log.step(1).id,2);
assert.equal(log.resumeLive().id,3);
assert.throws(()=>first.text="overwritten",TypeError);
assert.deepEqual(log.snapshot().map(row=>row.original),["hello one","hello two","hello three"]);
assert.equal(log.snapshot()[1].translations.cloud.error,"HTTP 429");
assert.throws(()=>log.append({id:3,text:"duplicate",at:5}),/Duplicate/);
log.clear();assert.equal(log.entries.length,0);
assert.equal(dedupeFinalOverlap("one two three four five six","two three four five six seven eight"),"seven eight");
assert.equal(dedupeFinalOverlap("yes yes yes","yes yes"),"yes yes");
assert.equal(dedupeFinalOverlap("","hello"),"hello");
const gate=new ProviderCircuit();
assert.equal(gate.canCall("cloud"),true);
gate.block("cloud","Rate limit reached");
assert.equal(gate.canCall("cloud"),false);
assert.equal(gate.reason("cloud"),"Rate limit reached");
assert.equal(gate.canCall("local"),true);
gate.reset("cloud");
assert.equal(gate.canCall("cloud"),true);
console.log("Canonical log, immutable source, focus cursor, conservative overlap and rate-limit circuit passed.");
