import assert from "node:assert/strict";
import {ParagraphBuilder} from "./paragraph-builder.js";
let jobs=new Map(), seq=0, commits=[], previews=[];
const schedule=(fn,ms)=>{const id=++seq;jobs.set(id,{fn,ms});return id;};
const unschedule=(id)=>jobs.delete(id);
const builder=new ParagraphBuilder({schedule,unschedule,onParagraph:p=>commits.push(p),
 onPreview:p=>previews.push(p),silenceMs:1200,maxWords:30});
builder.addFinal("שלום לכולם",{source:"he",target:"en",finalPerf:1});
builder.addFinal("זאת שיחה מתמשכת",{source:"he",target:"en",finalPerf:10});
assert.equal(commits.length,0);
assert.equal(builder.pending,"שלום לכולם זאת שיחה מתמשכת");
assert.equal(jobs.size,1,"Must debounce after each final result");
assert.equal([...jobs.values()][0].ms,1200);
[...jobs.values()][0].fn();
assert.equal(commits.length,1);
assert.equal(commits[0].text,"שלום לכולם זאת שיחה מתמשכת");
assert.equal(commits[0].reason,"silence");
assert.equal(commits[0].finalPerf,10);
assert.equal(builder.pending,"");
builder.addFinal("first",{source:"he",target:"en",finalPerf:15});
builder.addFinal("second",{source:"en",target:"he",finalPerf:20});
assert.equal(commits.length,2,"Must flush before language pair changes");
assert.equal(commits[1].reason,"language-change");
assert.equal(builder.pending,"second");
builder.flush("stop");
assert.equal(commits[2].text,"second");
builder.addFinal("discard",{source:"he",target:"en"});
builder.clear();
assert.equal(builder.pending,"");
assert.equal(jobs.size,0);
builder.setSilence(120);
assert.equal(builder.silenceMs,500,"Safe lower pause limit");
assert.ok(previews.includes("שלום לכולם זאת שיחה מתמשכת"));
console.log("ParagraphBuilder debounce, language separation, Stop flush, clear and safety limits passed.");
