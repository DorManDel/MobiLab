import assert from 'node:assert/strict';
import {stabilizeWarpPoints,estimateProfileVisibility} from './warp-geometry.js';
const source=Array.from({length:478},(_,i)=>({x:50+(i%19)*5,y:30+Math.floor(i/19)*4}));
const live=source.map(p=>({x:p.x+17,y:p.y+10}));
source[33]={x:100,y:100};source[263]={x:200,y:100};
live[33]={x:115,y:125};live[263]={x:255,y:135};
source[1]={x:151,y:135};live[1]={x:185,y:160};
source[13]={x:151,y:180};live[13]={x:240,y:220};
const gentle=stabilizeWarpPoints(source,live,0);
const expressive=stabilizeWarpPoints(source,live,1);
assert.equal(gentle.length,478);
assert.deepEqual(gentle[152],live[152],'jaw silhouette must follow live face');
assert.deepEqual(gentle[33],live[33],'left eye anchor aligned');
assert.deepEqual(gentle[263],live[263],'right eye anchor aligned');
assert.ok(Math.abs(expressive[13].x-live[13].x)<Math.abs(gentle[13].x-live[13].x),'expression slider should follow target more');
assert.ok(gentle.every(p=>Number.isFinite(p.x)&&Number.isFinite(p.y)));
assert.deepEqual(stabilizeWarpPoints([],[],.4),[]);
const front=live.map(p=>({...p}));front[1]={x:(front[33].x+front[263].x)/2,y:front[1].y};
const profile=front.map(p=>({...p}));profile[1]={x:front[33].x,y:front[1].y};
assert.equal(estimateProfileVisibility(front),1,'frontal nose keeps opacity');
assert.ok(estimateProfileVisibility(profile)<1,'profile nose should reduce visual distortion');
assert.ok(estimateProfileVisibility(profile)>=.24,'do not fully disappear');
console.log('FaceFX v0.6 geometry tests passed.');
